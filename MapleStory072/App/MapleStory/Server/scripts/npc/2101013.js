function start() {
    qfresh = true;
    if (qQuestAction(1, 0, 0)) return;
	cm.sendNext("#e梦岛欢迎你#n!");
	cm.dispose();
}

function action(mode, type, selection) {
    if (qQuestAction(mode, type, selection)) return;
}

