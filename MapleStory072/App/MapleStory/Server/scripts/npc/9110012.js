var totalWeight = 400000;
function start() {
    if (finished || status != -1) return;
    if (!cm.haveItem(ticket, 1)) { finished = true; cm.sendOk('请携带一张#v' + ticket + '##t' + ticket + '#再来。'); cm.dispose(); return; }
    status = 0;
    cm.sendYesNo('每次消耗一张#v' + ticket + '##t' + ticket + '#，随机获得一份物品。\r\n是否现在使用？');
}
function action(mode, type, selection) {
    if (finished) return;
    if (status != 0 || mode != 1) { finished = true; cm.dispose(); return; }
    finished = true;
    if (!cm.haveItem(ticket, 1)) { cm.sendOk('你的百宝券不足，没有扣除道具。'); cm.dispose(); return; }
    var roll = Math.floor(Math.random() * totalWeight);
    var chosen = null;
    for (var i = 0; i < pool.length; i++) { if (roll < pool[i][2]) { chosen = pool[i]; break; } }
    if (chosen == null) { cm.dispose(); return; }
    var id = chosen[0];
    var quantity = chosen[1] == 0 ? Math.floor(Math.random() * 50) + 1 : chosen[1];
    if (!cm.canHold(id, quantity)) { cm.sendOk('请先为抽中的物品留出足够的背包空间，没有扣除百宝券。'); cm.dispose(); return; }
    if (!cm.removeItem(ticket)) { cm.sendOk('未能扣除百宝券，请重新对话。'); cm.dispose(); return; }
    var before = cm.getPlayer().itemQuantity(id);
    try { cm.gainItem(id, quantity); } catch (error) {}
    if (cm.getPlayer().itemQuantity(id) < before + quantity) {
        cm.gainItem(ticket, 1); cm.sendOk('未能发放物品，已退回百宝券。');
    } else { cm.sendOk('你获得了#v' + id + '##t' + id + '# × ' + quantity + '。'); }
    cm.dispose();
}
